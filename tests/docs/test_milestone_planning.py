def _active_milestone_section() -> str:
    guide = GUIDE.read_text(encoding="utf-8")
    match = re.search(
        r"^## Active Milestone\s*\n(?P<body>.*?)(?=^## |\Z)",
        guide,
        re.MULTILINE | re.DOTALL,
    )
    if not match:
        raise AssertionError("docs/README.md must contain an Active Milestone section")
    return match.group("body")


def _active_plan_paths() -> tuple[Path, Path] | None:
    section = _active_milestone_section()
    if re.search(r"^\*\*None\.\*\*", section, re.MULTILINE):
        return None
    match = re.search(
        r"milestones/(\d+-[^)\s]+)/plan\.html",
        section,
    )
    if not match:
        raise AssertionError("docs/README.md must link an active milestone plan.html")
    slug = match.group(1)
    plan_md = MILESTONES / slug / "plan.md"
    plan_html = MILESTONES / slug / "plan.html"
    return plan_md, plan_html


class MilestonePlanningTests(unittest.TestCase):
    def test_rendered_contract_identifies_current_markdown_source(self) -> None:
        source = CONTRACT_SOURCE.read_text(encoding="utf-8")
        rendered = CONTRACT_RENDER.read_text(encoding="utf-8")
        expected_digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
        match = re.search(
            r'<meta name="source-sha256" content="([a-f0-9]{64})">',
            rendered,
        )
        self.assertIsNotNone(match)
        assert match is not None
        self.assertEqual(match.group(1), expected_digest)
        self.assertIn("Generated by docs/render_markdown.py", rendered)

    def test_active_plan_markdown_is_canonical_and_html_is_generated(self) -> None:
        paths = _active_plan_paths()
        if paths is None:
            return
        plan_md, plan_html = paths
        self.assertTrue(plan_md.is_file(), f"missing canonical plan: {plan_md}")
        self.assertTrue(plan_html.is_file(), f"missing generated plan: {plan_html}")
        source = plan_md.read_text(encoding="utf-8")
        rendered = plan_html.read_text(encoding="utf-8")
        expected = hashlib.sha256(source.encode("utf-8")).hexdigest()
        match = re.search(
            r'<meta name="source-sha256" content="([a-f0-9]{64})">',
            rendered,
        )
        self.assertIsNotNone(match)
        assert match is not None
        self.assertEqual(match.group(1), expected)
        self.assertIn("Generated by docs/render_markdown.py", rendered)
        self.assertIn("Canonical source:", rendered)

