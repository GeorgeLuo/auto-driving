class _SourceReader(Protocol):
    def files(self) -> list[str]:
        ...

    def read_text(self, relative_path: str) -> str:
        ...


class _MappingReader:
    """Read an explicit path → text mapping with no Git dependency."""

    def __init__(self, sources: Mapping[str, str]) -> None:
        self._sources = {path.replace("\\", "/"): text for path, text in sources.items()}

    def files(self) -> list[str]:
        return sorted(self._sources)

    def read_text(self, relative_path: str) -> str:
        return self._sources.get(relative_path.replace("\\", "/"), "")


@dataclass(frozen=True)
class _ResolvedTree:
    root: Path
    repo_root: Path | None
    scope_rel: str
    ref: str | None
    sha: str | None


class _TreeReader:
    """Read either the working tree or an immutable Git revision."""

    def __init__(self, tree: _ResolvedTree) -> None:
        self.tree = tree
        self._ref_contents: dict[str, str] | None = None

    def files(self) -> list[str]:
        if self.tree.ref is None:
            root = self.tree.root
            if root.is_file():
                return [root.name]
            paths: list[str] = []
            for path in root.rglob("*"):
                if not path.is_file():
                    continue
                if ".git" in path.parts or "__pycache__" in path.parts:
                    continue
                paths.append(path.relative_to(root).as_posix())
            return sorted(paths)

        prefix = [] if self.tree.scope_rel in {"", "."} else [self.tree.scope_rel]
        output = _git(
            ["ls-tree", "-r", "--name-only", self.tree.ref, "--", *prefix],
            cwd=self.tree.repo_root,
        )
        paths = []
        scope = PurePosixPath(self.tree.scope_rel) if self.tree.scope_rel not in {"", "."} else None
        for line in output.splitlines():
            repo_path = PurePosixPath(line.strip())
            if scope is None:
                relative = repo_path
            elif self.tree.root.is_file():
                if repo_path != scope:
                    continue
                relative = PurePosixPath(repo_path.name)
            else:
                try:
                    relative = repo_path.relative_to(scope)
                except ValueError:
                    continue
            paths.append(relative.as_posix())
        return sorted(paths)

    def read_text(self, relative_path: str) -> str:
        if self.tree.ref is None:
            path = self.tree.root if self.tree.root.is_file() else self.tree.root / relative_path
            try:
                return path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                return path.read_bytes().decode("utf-8", errors="replace")

        repo_path = PurePosixPath(relative_path)
        if self.tree.scope_rel not in {"", "."}:
            repo_path = PurePosixPath(self.tree.scope_rel) / repo_path
        try:
            if self._ref_contents is None:
                self._ref_contents = self._load_ref_contents()
            relative = relative_path.replace("\\", "/")
            if relative in self._ref_contents:
                return self._ref_contents[relative]
            return _git_bytes(
                ["show", f"{self.tree.ref}:{repo_path.as_posix()}"],
                cwd=self.tree.repo_root,
            ).decode("utf-8", errors="replace")
        except AnalysisError:
            return ""

    def _load_ref_contents(self) -> dict[str, str]:
        """Batch-read one revision so historical backtests avoid one process per file."""

        scope = [] if self.tree.scope_rel in {"", "."} else [self.tree.scope_rel]
        archive = _git_bytes(
            ["archive", "--format=tar", self.tree.ref, "--", *scope],
            cwd=self.tree.repo_root,
        )
        contents: dict[str, str] = {}
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as tar:
            scope_path = PurePosixPath(self.tree.scope_rel)
            for member in tar.getmembers():
                if not member.isfile():
                    continue
                name = PurePosixPath(member.name)
                if self.tree.root.is_file():
                    if name.name != scope_path.name:
                        continue
                    relative = name.name
                elif self.tree.scope_rel in {"", "."}:
                    relative = name.as_posix()
                else:
                    try:
                        relative = name.relative_to(scope_path).as_posix()
                    except ValueError:
                        continue
                extracted = tar.extractfile(member)
                if extracted is not None:
                    contents[relative] = extracted.read().decode("utf-8", errors="replace")
        return contents


def analyze_tree(
    path: str | Path | Sequence[str | Path] = ".",
    *,
    ref: str | None = None,
    config: AnalyzerConfig | None = None,
) -> Report:
    """Measure files, directories, or one Git revision.

    Git is required only when ``ref`` is set.  Otherwise any file or directory
    of text can be measured, including trees that are not repositories.
    """

    paths = _as_paths(path)
    policy = config or AnalyzerConfig()
    if ref is not None:
        if len(paths) != 1:
            raise AnalysisError("revision mode requires a single path")
        tree = _resolve_tree(paths[0], ref=ref)
        reader: _SourceReader = _TreeReader(tree)
        inventory = _inventory(reader, policy)
        head = _measure_snapshot(reader, inventory)
        identity = _identity(
            mode="tree",
            analyzed_path=tree.scope_rel,
            head_sha=tree.sha,
            repo_root=tree.repo_root,
            config=policy,
            working_tree_digest=None,
        )
        return Report(
            identity=identity,
            source_inventory=inventory,
            head=head,
            observations=_observations(head, None, None),
            factors=measure_factors(_factor_sources(reader, inventory)),
            configuration=policy.canonical(),
        )
    analyzed_path, sources = _sources_from_paths(paths)
    return analyze_sources(sources, config=policy, analyzed_path=analyzed_path)


def analyze_sources(
    sources: Mapping[str, str],
    *,
    config: AnalyzerConfig | None = None,
    analyzed_path: str = ".",
) -> Report:
    """Measure an explicit path → text mapping. Git is not required."""

    policy = config or AnalyzerConfig()
    reader = _MappingReader(sources)
    inventory = _inventory(reader, policy)
    head = _measure_snapshot(reader, inventory)
    identity = _identity(
        mode="tree",
        analyzed_path=analyzed_path,
        head_sha=None,
        repo_root=None,
        config=policy,
        working_tree_digest=_sources_digest(reader, inventory),
    )
    return Report(
        identity=identity,
        source_inventory=inventory,
        head=head,
        observations=_observations(head, None, None),
        factors=measure_factors(_factor_sources(reader, inventory)),
        configuration=policy.canonical(),
    )


def analyze_diff(
    base: str,
    head: str,
    *,
    path: str | Path = ".",
    config: AnalyzerConfig | None = None,
) -> Report:
    """Measure a reproducible base→head Git change."""

    policy = config or AnalyzerConfig()
    root_path = Path(path)
    repo_root = _find_repo_root(root_path)
    if repo_root is None:
        raise AnalysisError("diff mode requires a path inside a Git repository")
    base_tree = _resolve_tree(root_path, ref=base, repo_root=repo_root)
    head_tree = _resolve_tree(root_path, ref=head, repo_root=repo_root)
    base_reader = _TreeReader(base_tree)
    head_reader = _TreeReader(head_tree)
    base_inventory = _inventory(base_reader, policy)
    head_inventory = _inventory(head_reader, policy)
    base_snapshot = _measure_snapshot(base_reader, base_inventory)
    head_snapshot = _measure_snapshot(head_reader, head_inventory)
    file_diffs = _read_git_diff(
        repo_root=repo_root,
        base_sha=base_tree.sha or base,
        head_sha=head_tree.sha or head,
        scope_rel=head_tree.scope_rel,
    )
    file_diffs = _scope_file_diffs(file_diffs, head_tree.scope_rel)
    diff = _derive_diff(base_snapshot, head_snapshot, base_inventory, head_inventory, file_diffs)
    identity = _identity(
        mode="diff",
        analyzed_path=head_tree.scope_rel,
        head_sha=head_tree.sha,
        repo_root=head_tree.repo_root,
        base_sha=base_tree.sha,
        config=policy,
        working_tree_digest=None,
    )
    return Report(
        identity=identity,
        source_inventory=head_inventory,
        head=head_snapshot,
        base=base_snapshot,
        diff=diff,
        observations=_observations(head_snapshot, base_snapshot, diff),
        factors=compare_factors(
            measure_factors(_factor_sources(base_reader, base_inventory)),
            measure_factors(_factor_sources(head_reader, head_inventory)),
            set(diff.changed_files),
        ),
        configuration=policy.canonical(),
    )


def _factor_sources(reader: _SourceReader, inventory: list[SourceFile]) -> dict[str, str]:
    return {
        item.path: reader.read_text(item.path)
        for item in inventory
        if item.included and item.language == "python"
    }


