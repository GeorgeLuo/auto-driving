def report_to_dict(report: Report) -> dict[str, Any]:
    """Return a stable JSON-compatible report representation."""

    payload = asdict(report)
    payload["identity"]["report_schema"] = REPORT_SCHEMA
    payload["source_inventory"] = sorted(
        payload["source_inventory"], key=lambda item: item["path"]
    )
    payload["head"]["callables"] = sorted(
        payload["head"]["callables"], key=lambda item: (item["path"], item["qualified_name"])
    )
    if payload.get("base"):
        payload["base"]["callables"] = sorted(
            payload["base"]["callables"], key=lambda item: (item["path"], item["qualified_name"])
        )
    return _sort_json_value(payload)


