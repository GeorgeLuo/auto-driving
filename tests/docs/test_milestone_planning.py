    def test_completion_usage_starts_with_primary_demonstration(self) -> None:
        paths = _active_plan_paths()
        if paths is None:
            return
        plan_md, _ = paths
        table = parse_table(
            plan_md.read_text(encoding="utf-8"),
            "## Completion Usage",
        )
        self.assertEqual(
            table.header,
            ("Workflow", "Starting state", "Execution", "Success signal", "Criteria"),
        )
        self.assertTrue(table.rows, "Completion Usage must contain workflows")
        self.assertEqual(table.rows[0][0], "Primary demonstration")

    def test_active_plan_has_one_current_frontier_and_at_most_one_next(self) -> None:
        paths = _active_plan_paths()
        if paths is None:
            return
        plan_md, _ = paths
        state = validate_plan_path(plan_md)
        self.assertFalse(state.current.is_empty)
        # Terminal closeout may leave next empty; otherwise at most one named next.
        if not state.next_frontier.is_empty:
            self.assertTrue(state.next_frontier.fields["review question"])
        self.assertTrue(state.current.fields["review question"])
        self.assertTrue(state.milestone_branch.startswith("milestone/"))

    def test_active_plan_exit_criteria_use_stable_ids(self) -> None:
        paths = _active_plan_paths()
        if paths is None:
            return
        plan_md, _ = paths
        state = validate_plan_path(plan_md)
        ids = [row[0] for row in state.criteria.rows]
        self.assertGreaterEqual(len(ids), 3)
        self.assertEqual(len(ids), len(set(ids)), "exit criteria IDs must be unique")

