    def test_git_diff_reports_changed_shape_and_actionable_targets(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            self._git(root, "init", "-q")
            self._git(root, "config", "user.email", "qca@example.test")
            self._git(root, "config", "user.name", "QCA Tests")
            (root / "app.py").write_text(
                "def choose(value):\n    return value\n", encoding="utf-8"
            )
            self._git(root, "add", ".")
            self._git(root, "commit", "-qm", "base")
            base = self._git(root, "rev-parse", "HEAD").strip()
            (root / "app.py").write_text(
                """import external_lib\n\n\ndef choose(value, fallback=False):\n    if value:\n        if fallback:\n            return value\n        return external_lib.normalize(value)\n    return None\n""",
                encoding="utf-8",
            )
            self._git(root, "add", "app.py")
            self._git(root, "commit", "-qm", "head")
            head = self._git(root, "rev-parse", "HEAD").strip()

            payload = report_to_dict(analyze_diff(base, head, path=root))
            diff = payload["diff"]

            self.assertEqual(diff["changed_files"], ["app.py"])
            self.assertEqual(diff["file_changes"][0]["source_class"], "production")
            self.assertTrue(diff["file_changes"][0]["included"])
            self.assertGreater(diff["added_lines"], 0)
            self.assertGreater(diff["deleted_lines"], 0)
            self.assertEqual(diff["churn"], diff["added_lines"] + diff["deleted_lines"])
            self.assertEqual(diff["decision_burden_delta"], 2)
            self.assertEqual(diff["new_import_edges"], ["app.py->external_lib"])
            callable_target = next(
                target
                for target in diff["review_targets"]
                if target["kind"] == "callable"
            )
            self.assertEqual(callable_target["action"], "inspect_callable")
            self.assertIn("decision count increased by 2", callable_target["reasons"])
            self.assertTrue(
                any(
                    target["kind"] == "dependency"
                    and target["edge"] == "app.py->external_lib"
                    for target in diff["review_targets"]
                )
            )

    def test_report_json_is_reproducible_for_same_tree(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "app.py").write_text("VALUE = 3\n", encoding="utf-8")
            first = report_to_dict(analyze_tree(root))
            second = report_to_dict(analyze_tree(root))
            self.assertEqual(first, second)
            self.assertIsNone(first["identity"]["head_sha"])
            self.assertTrue(first["identity"]["working_tree_digest"])
            (root / "untracked.py").write_text("EXTRA = 1\n", encoding="utf-8")
            changed = report_to_dict(analyze_tree(root))
            self.assertNotEqual(
                first["identity"]["working_tree_digest"],
                changed["identity"]["working_tree_digest"],
            )
            (root / "notes.txt").write_text("one\n", encoding="utf-8")
            first_notes = report_to_dict(analyze_tree(root))
            (root / "notes.txt").write_text("two\n", encoding="utf-8")
            second_notes = report_to_dict(analyze_tree(root))
            self.assertNotEqual(
                first_notes["identity"]["working_tree_digest"],
                second_notes["identity"]["working_tree_digest"],
            )
            completed = subprocess.run(
                [sys.executable, "-m", "qca", "analyze", str(root)],
                cwd=Path(__file__).resolve().parents[2],
                check=False,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertIn("working-tree digest:", completed.stdout)

