    def test_git_diff_treats_rename_as_delete_plus_add_and_keeps_deletion_ranges(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            self._git(root, "init", "-q")
            self._git(root, "config", "user.email", "qca@example.test")
            self._git(root, "config", "user.name", "QCA Tests")
            (root / "old.py").write_text("def old():\n    return 1\n", encoding="utf-8")
            (root / "delete.py").write_text("def gone():\n    return 0\n", encoding="utf-8")
            self._git(root, "add", ".")
            self._git(root, "commit", "-qm", "base")
            base = self._git(root, "rev-parse", "HEAD").strip()
            os.rename(root / "old.py", root / "new.py")
            os.unlink(root / "delete.py")
            self._git(root, "add", "-A")
            self._git(root, "commit", "-qm", "head")
            head = self._git(root, "rev-parse", "HEAD").strip()

            payload = report_to_dict(analyze_diff(base, head, path=root))
            diff = payload["diff"]
            self.assertEqual(diff["changed_files"], ["delete.py", "new.py", "old.py"])
            changes = {(item["path"], item["qualified_name"]): item for item in diff["changed_callables"]}
            self.assertIsNone(changes[("new.py", "old")]["before"])
            self.assertIsNone(changes[("old.py", "old")]["after"])
            self.assertIsNone(changes[("delete.py", "gone")]["after"])

